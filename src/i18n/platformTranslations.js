/**
 * Localize Common Business Values, Enums, Roadmap Stages & Task Text
 */
export function localizeBusinessValue(value, lang = 'en') {
  if (!value || typeof value !== 'string') return value || '—';
  if (lang === 'en') return value;

  const langMap = BUSINESS_VALUE_MAP[lang];
  if (langMap && langMap[value]) {
    return langMap[value];
  }

  // Check if string contains standard substrings like "Team Members"
  if (lang === 'bn' && value.includes('Team Members')) {
    return value.replace('Team Members', 'জন সদস্য');
  }
  if (lang === 'hi' && value.includes('Team Members')) {
    return value.replace('Team Members', 'सदस्य');
  }
  if (lang === 'mr' && value.includes('Team Members')) {
    return value.replace('Team Members', 'सदस्य');
  }

  // Handle stage names
  const stageUpper = value.toUpperCase();
  if (stageUpper === 'IDEA') {
    if (lang === 'bn') return 'ধারণা (IDEA)';
    if (lang === 'hi') return 'विचार (IDEA)';
    if (lang === 'mr') return 'संकल्पना (IDEA)';
  }

  return value;
}
