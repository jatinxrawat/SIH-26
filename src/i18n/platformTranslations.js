/**
 * Localize Common Business Values, Enums, Roadmap Stages & Task Text
 */
export function localizeBusinessValue(value, lang = 'en') {
  if (!value || typeof value !== 'string') return value || '—';
  if (lang === 'en') return value;

  const trimmed = value.trim();

  // 1. Master Scheme Names Map check
  if (SCHEME_NAMES_MAP?.[lang]?.[trimmed]) {
    return SCHEME_NAMES_MAP[lang][trimmed];
  }

  // 2. Master Scheme Benefits Map check
  if (SCHEME_BENEFITS_MAP?.[lang]?.[trimmed]) {
    return SCHEME_BENEFITS_MAP[lang][trimmed];
  }

  // 3. Direct business value map check
  const langMap = BUSINESS_VALUE_MAP[lang];
  if (langMap && langMap[trimmed]) {
    return langMap[trimmed];
  }

  // 4. Normalized check for apostrophes (straight vs curly)
  const normVal = trimmed.replace(/’/g, "'");
  if (SCHEME_NAMES_MAP?.[lang]?.[normVal]) {
    return SCHEME_NAMES_MAP[lang][normVal];
  }
  if (SCHEME_BENEFITS_MAP?.[lang]?.[normVal]) {
    return SCHEME_BENEFITS_MAP[lang][normVal];
  }
  if (langMap && langMap[normVal]) {
    return langMap[normVal];
  }

  // Dynamic regex for blocker reasons: Required to complete "..."
  const reqMatch = value.match(/^Required to complete\s+["'](.+?)["']$/i);
  if (reqMatch) {
    const localizedTask = localizeBusinessValue(reqMatch[1], lang);
    if (lang === 'hi') return `"${localizedTask}" को पूरा करने के लिए आवश्यक`;
    if (lang === 'bn') return `"${localizedTask}" সম্পন্ন করার জন্য প্রয়োজনীয়`;
    if (lang === 'mr') return `"${localizedTask}" पूर्ण करण्यासाठी आवश्यक`;
  }

  // Dynamic regex for time estimates: e.g. "1 day", "2-3 days"
  const dayMatch = value.match(/^(\d+(?:-\d+)?)\s*(?:days?|day)$/i);
  if (dayMatch) {
    if (lang === 'hi') return `${dayMatch[1]} दिन`;
    if (lang === 'bn') return `${dayMatch[1]} দিন`;
    if (lang === 'mr') return `${dayMatch[1]} दिवस`;
  }

  // Check if string contains standard substrings like "Team Members"
  if (lang === 'bn' && value.includes('Team Members')) {
    return value.replace('Team Members', 'জন সদস্য');
  }
  if (lang === 'hi' && value.includes('Team Members')) {
    return value.replace('Team Members', 'सदस्य');
  }
  if (lang === 'mr' && value.includes('Team Members')) {
    return value.replace('Team Members', 'सदस्य');
  }

  // Handle stage names
  const stageUpper = value.toUpperCase();
  if (stageUpper === 'IDEA') {
    if (lang === 'bn') return 'ধারণা (IDEA)';
    if (lang === 'hi') return 'विचार (IDEA)';
    if (lang === 'mr') return 'संकल्पना (IDEA)';
  }

  return value;
}
